#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recovered_tables_keep_their_published_sizes() {
        let reasons = 0..=u16::MAX;
        assert_eq!(
            reasons
                .clone()
                .filter(|reason| shutdown_reason_result(*reason) != 0x8003_0000)
                .count(),
            195
        );
        assert_eq!(
            reasons
                .filter(|reason| shutdown_reason_outcome(*reason).0 != 0x35)
                .count(),
            24
        );
    }
}
